"""界面判据与区域表（相对坐标 0~1，基准 = 游戏客户区 1920x1080）。

设计原则：
1. 能用文字判的就不用模板。这个游戏 UI 文字大、对比高（白字压在深色牌上），
   OCR 比模板匹配稳，也不怕分辨率变化。
2. 区域只用来**缩小搜索范围**，不用来精确定位按钮。
3. 名字写错要直接报错，不要静默退化成全屏搜索（ok-Onmyoji 的教训）。
"""

